<?php

namespace App\Models;

use Database\Factories\ReferralCodeFactory;
use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsTo;
use Illuminate\Database\Eloquent\Relations\HasMany;
use Illuminate\Support\Str;

class ReferralCode extends Model
{
    /** @use HasFactory<ReferralCodeFactory> */
    use HasFactory;

    /**
     * The attributes that are mass assignable.
     *
     * @var list<string>
     */
    protected $fillable = [
        'code',
        'referrer_id',
        'reward_sessions_referrer',
        'reward_sessions_referee',
        'uses_remaining',
        'expires_at',
    ];

    /**
     * Get the attributes that should be cast.
     *
     * @return array<string, string>
     */
    protected function casts(): array
    {
        return [
            'reward_sessions_referrer' => 'integer',
            'reward_sessions_referee' => 'integer',
            'uses_remaining' => 'integer',
            'expires_at' => 'datetime',
        ];
    }

    /**
     * Get the user this code belongs to.
     */
    public function referrer(): BelongsTo
    {
        return $this->belongsTo(User::class, 'referrer_id');
    }

    /**
     * Get the session-credit-ledger entries generated by redemptions of
     * this code (both the referrer's and each referee's bonus).
     */
    public function ledgerEntries(): HasMany
    {
        return $this->hasMany(SessionCreditLedgerEntry::class);
    }

    /**
     * Get just the referee side of each redemption — i.e. who this code
     * was used by, excluding the referrer's own bonus-credit entries.
     */
    public function refereeCredits(): HasMany
    {
        return $this->ledgerEntries()->where('user_id', '!=', $this->referrer_id);
    }

    /**
     * Whether this code can still be redeemed right now — not expired,
     * and either has no redemption cap or still has uses left.
     */
    public function isRedeemable(): bool
    {
        if ($this->expires_at && $this->expires_at->isPast()) {
            return false;
        }

        return $this->uses_remaining === null || $this->uses_remaining > 0;
    }

    /**
     * Get this user's own referral code, creating one on first request.
     */
    public static function forUser(User $user): self
    {
        return static::firstOrCreate(
            ['referrer_id' => $user->id],
            ['code' => static::generateUniqueCode()],
        );
    }

    /**
     * Generate a short, unique, uppercase alphanumeric code.
     */
    private static function generateUniqueCode(): string
    {
        do {
            $code = Str::upper(Str::random(8));
        } while (static::where('code', $code)->exists());

        return $code;
    }
}
