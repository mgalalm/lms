<?php

namespace App\Enums;

/**
 * Every admin-configurable application setting. Adding a case here is all
 * that's needed to surface a new setting — App\Filament\Pages\Settings
 * builds its form from these, and Setting::get() falls back to default()
 * whenever a key has never been saved.
 */
enum SettingKey: string
{
    case QuizMaxGenerations = 'quiz.max_generations';

    /**
     * Value used when an admin has never saved this setting.
     */
    public function default(): mixed
    {
        return match ($this) {
            self::QuizMaxGenerations => 2,
        };
    }

    public function label(): string
    {
        return match ($this) {
            self::QuizMaxGenerations => 'Quiz generations per lesson',
        };
    }

    public function helperText(): string
    {
        return match ($this) {
            self::QuizMaxGenerations => 'How many times a lesson quiz may be generated by AI in total, '
                .'counting the first generation. Once a quiz reaches this limit it can never be regenerated '
                .'again — the count is not reset by editing the slide text. Admins can always keep editing '
                .'questions by hand.',
        };
    }

    /**
     * Group heading this setting renders under on the Settings page.
     */
    public function section(): string
    {
        return match ($this) {
            self::QuizMaxGenerations => 'Lesson Quizzes',
        };
    }
}
